-- ============================================================================
-- 5. PROCESS_PURCHASE STORED PROCEDURE
-- Atomic single-item vending: uses row-level locking (SELECT FOR UPDATE)
-- to verify stock, deduct inventory, and record the sale in a single ACID transaction.
-- ============================================================================
create or replace function public.process_purchase(
    p_slot text,
    p_paid integer,
    p_transaction_id text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_item inventory%rowtype;
    v_change integer;
begin
    select * into v_item
    from inventory
    where slot = upper(p_slot)
    for update;

    if not found then
        return jsonb_build_object('success', false, 'error', 'Unknown slot.');
    end if;

    if v_item.stock <= 0 then
        return jsonb_build_object('success', false, 'error', 'Item is out of stock.');
    end if;

    if p_paid < v_item.price then
        return jsonb_build_object(
            'success', false,
            'error', format('Insufficient balance: paid ₹%s, price ₹%s', p_paid, v_item.price)
        );
    end if;

    v_change := p_paid - v_item.price;

    update inventory set stock = stock - 1 where slot = v_item.slot;

    insert into sales(slot,item_name,price,paid,change_amount,transaction_id)
    values(v_item.slot,v_item.name,v_item.price,p_paid,v_change,p_transaction_id);

    return jsonb_build_object(
        'success', true,
        'slot', v_item.slot,
        'name', v_item.name,
        'price', v_item.price,
        'stock_after', v_item.stock - 1,
        'change', v_change
    );
end;
$$;


-- ============================================================================
-- 6. PROCESS_CART_PURCHASE STORED PROCEDURE
-- Atomic multi-item cart vending: locks all requested inventory rows,
-- validates sufficient stock, calculates gross total, subtracts CFG combo deal
-- discount (p_discount_amount), verifies paid >= total, deducts stock, and records sales.
-- ============================================================================
create or replace function public.process_cart_purchase(
    p_cart jsonb,
    p_paid integer,
    p_transaction_id text,
    p_discount_amount integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    r jsonb;
    v_item inventory%rowtype;
    v_slot text;
    v_qty integer;
    v_total integer := 0;
    v_gross_total integer := 0;
    v_change integer;
    v_items jsonb := '[]'::jsonb;
    v_discount_recorded boolean := false;
begin
    if p_cart is null or jsonb_array_length(p_cart) = 0 then
        return jsonb_build_object('success', false, 'error', 'Cart is empty.');
    end if;

    -- Lock and validate every requested item before changing anything.
    for r in select * from jsonb_array_elements(p_cart)
    loop
        v_slot := upper(r->>'slot');
        v_qty := (r->>'quantity')::integer;

        if v_qty <= 0 then
            return jsonb_build_object('success', false, 'error', 'Invalid cart quantity.');
        end if;

        select * into v_item from inventory where slot = v_slot for update;
        if not found then
            return jsonb_build_object('success', false, 'error', 'Unknown slot: ' || v_slot);
        end if;

        if v_item.stock < v_qty then
            return jsonb_build_object(
                'success', false,
                'error', format('Only %s %s left in stock.', v_item.stock, v_item.name)
            );
        end if;

        v_total := v_total + (v_item.price * v_qty);
    end loop;

    v_gross_total := v_total;
    if p_discount_amount < 0 or p_discount_amount > v_gross_total then
        return jsonb_build_object('success', false, 'error', 'Invalid combo discount amount.');
    end if;
    v_total := v_gross_total - p_discount_amount;

    if p_paid < v_total then
        return jsonb_build_object(
            'success', false,
            'error', format('Insufficient balance: paid ₹%s, cart total ₹%s', p_paid, v_total)
        );
    end if;

    v_change := p_paid - v_total;

    for r in select * from jsonb_array_elements(p_cart)
    loop
        v_slot := upper(r->>'slot');
        v_qty := (r->>'quantity')::integer;

        select * into v_item from inventory where slot = v_slot for update;

        update inventory
        set stock = stock - v_qty
        where slot = v_slot;

        -- One row per unit keeps the existing daily-sales model intact.
        for i in 1..v_qty loop
            insert into sales(slot,item_name,price,paid,change_amount,transaction_id,discount_amount)
            values(
                v_item.slot,v_item.name,v_item.price,p_paid,v_change,p_transaction_id,
                case when not v_discount_recorded then p_discount_amount else 0 end
            );
            v_discount_recorded := true;
        end loop;

        v_items := v_items || jsonb_build_array(
            jsonb_build_object(
                'slot', v_item.slot,
                'name', v_item.name,
                'stock', v_item.stock - v_qty,
                'quantity_bought', v_qty,
                'line_total', v_item.price * v_qty
            )
        );
    end loop;

    return jsonb_build_object(
        'success', true,
        'items', v_items,
        'gross_total', v_gross_total,
        'discount_amount', p_discount_amount,
        'total', v_total,
        'change', v_change
    );
end;
$$;


-- ============================================================================
-- 7. COLLECT_END_DAY STORED PROCEDURE
-- Daily collection routine: aggregates today's sales (Asia/Kolkata timezone),
-- increments the singleton receipt counter, deletes today's sales records,
-- and returns a formatted audit receipt.
-- ============================================================================
create or replace function public.collect_end_day(p_day date)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_count integer;
    v_total integer;
    v_received integer;
    v_change integer;
    v_next_count integer;
    v_items jsonb;
    v_sales jsonb;
begin
    select count(*), coalesce(sum(price - discount_amount),0), coalesce(sum(paid),0), coalesce(sum(change_amount),0)
    into v_count, v_total, v_received, v_change
    from sales
    where sale_time >= (p_day::timestamp at time zone 'Asia/Kolkata')
      and sale_time < ((p_day + 1)::timestamp at time zone 'Asia/Kolkata');

    if v_count = 0 then
        return jsonb_build_object('success', false, 'error', 'No sales recorded today.');
    end if;

    select coalesce(jsonb_agg(jsonb_build_object('item',item_name,'quantity',qty) order by item_name),'[]'::jsonb)
    into v_items
    from (
        select item_name, count(*) as qty
        from sales
        where sale_time >= (p_day::timestamp at time zone 'Asia/Kolkata')
          and sale_time < ((p_day + 1)::timestamp at time zone 'Asia/Kolkata')
        group by item_name
    ) s;

    select receipt_count + 1 into v_next_count
    from machine_counter
    where id = 1
    for update;

    delete from sales
    where sale_time >= (p_day::timestamp at time zone 'Asia/Kolkata')
      and sale_time < ((p_day + 1)::timestamp at time zone 'Asia/Kolkata');

    update machine_counter
    set receipt_count = v_next_count,
        last_receipt_date = p_day
    where id = 1;

    return jsonb_build_object(
        'success', true,
        'receipt_count', v_next_count,
        'date', p_day::text,
        'transactions', v_count,
        'total_sales', v_total,
        'cash_received', v_received,
        'change_out', v_change,
        'items_sold', v_items,
        'deleted_rows', v_count,
        'receipt', jsonb_build_array(
            'SMARTVEND - END OF DAY',
            'DATE        : ' || p_day::text,
            'COLLECTION #: ' || v_next_count::text,
            'TRANSACTIONS: ' || v_count::text,
            'SALES TOTAL : ₹' || v_total::text,
            'CASH IN     : ₹' || v_received::text,
            'CHANGE OUT  : ₹' || v_change::text,
            'DAILY SALES DATA CLEARED'
        )
    );
end;
$$;


-- ============================================================================
-- 8. RESET_MACHINE STORED PROCEDURE (Dev/Demo Only)
-- Resets sales, repopulates initial catalog items, and resets counter to 0.
-- ============================================================================
create or replace function public.reset_machine()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
    delete from sales;
    delete from inventory;

    insert into inventory(slot,name,price,stock,category,icon)
    values
    ('A1','Water',20,10,'beverage','💧'),
    ('A2','Juice',30,8,'beverage','🧃'),
    ('A3','Soda',25,6,'beverage','🥤'),
    ('B1','Chips',20,10,'snack','🍟'),
    ('B2','Cookies',15,12,'snack','🍪'),
    ('B3','Chocolate',25,7,'snack','🍫');

    update machine_counter
    set receipt_count = 0, last_receipt_date = null
    where id = 1;

    return jsonb_build_object('success', true);
end;
$$;

