-- ============================================================================
-- 1. INVENTORY TABLE
-- Stores product catalog: slot ID (PK), item name, unit price, current stock,
-- category ('snack' or 'beverage' used as CFG terminals), and emoji icon.
-- ============================================================================
create table if not exists public.inventory (
    slot text primary key,
    name text not null,
    price integer not null check (price > 0),
    stock integer not null default 0 check (stock >= 0),
    category text not null,
    icon text
);

-- ============================================================================
-- 2. SALES LEDGER TABLE
-- Audit log recording every completed purchase, payment, change returned,
-- and combo deal discount applied.
-- ============================================================================
create table if not exists public.sales (
    id bigint generated by default as identity primary key,
    sale_time timestamptz not null default now(),
    slot text not null,
    item_name text not null,
    price integer not null,
    paid integer not null,
    change_amount integer not null,
    transaction_id text not null
);

create index if not exists sales_sale_time_idx on public.sales(sale_time);
create index if not exists sales_transaction_id_idx on public.sales(transaction_id);

-- ============================================================================
-- 3. MACHINE COUNTER TABLE
-- Singleton row (id = 1) tracking total daily collection receipts issued.
-- ============================================================================
create table if not exists public.machine_counter (
    id integer primary key check (id = 1),
    receipt_count integer not null default 0,
    last_receipt_date date
);

-- ============================================================================
-- 4. COMBO DEAL CONFIG TABLE (Unit V CFG)
-- Singleton row (id = 1) storing active BNF grammar rules and discount map.
